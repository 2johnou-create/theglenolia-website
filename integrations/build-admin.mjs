import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {renderEmail,languages} from './email-render.mjs';
import editions from './editions.json' with {type:'json'};
const ui=new URL('./admin-ui/',import.meta.url);
const contents=await Promise.all(['index.html','admin.css','admin.js','programme-admin.js'].map(p=>readFile(new URL(p,ui),'utf8')));
await writeFile(new URL('./admin-assets.mjs',import.meta.url),'// Generated by build-admin.mjs\n'+contents.map((s,i)=>`export const ${['html','css','js','programmeJs'][i]}=${JSON.stringify(s)};`).join('\n')+'\n');
const previews=new URL('./edm-previews/',import.meta.url);await mkdir(previews,{recursive:true});
for(const edition of editions)for(const language of languages)await writeFile(new URL(`${edition.id}-${language}.html`,previews),renderEmail(edition,language,{preview:true}));
console.log('Prepared protected admin assets and nine email previews.');
